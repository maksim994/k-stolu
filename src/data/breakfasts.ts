const a = (
  ingredientId: string,
  quantity: number | null,
  unit: Amount["unit"] = "г",
  note = "",
  optional = false,
): Amount => ({ ingredientId, quantity, unit, note, optional });
const step = (title: string, text: string, minutes?: number): Step => ({
  title,
  text,
  ...(minutes === undefined ? {} : { minutes }),
});
const method = (
  id: string,
  name: string,
  equipment: Equipment[],
  prepMinutes: number,
  cookMinutes: number,
  ingredients: Amount[],
  steps: Step[],
  note = "",
): Variant => ({
  id,
  name,
  equipment,
  servings: 2,
  prepMinutes,
  cookMinutes,
  ingredients,
  steps,
  note,
});
